"""Regenerate include/root_ca.h from the Mozilla CA bundle shipped with certifi.

    pip install certifi && python scripts/gen_root_ca.py

Run it when Azure changes the root its *.azurewebsites.net chain ends at, then check:
    openssl s_client -connect <app>.azurewebsites.net:443 -showcerts
"""

import pathlib
import re

import certifi

ROOTS = [
    # *.azurewebsites.net chains to this root (checked 2026-10-30).
    "DigiCert Global Root G2",
    # Fallback in case Azure moves its chain to Microsoft's own root.
    "Microsoft RSA Root Certificate Authority 2017",
]

bundle = pathlib.Path(certifi.where()).read_text(encoding="ascii")
certs = dict(
    re.findall(
        r'# Label: "([^"]*)"\n(?:#[^\n]*\n)*(-----BEGIN CERTIFICATE-----.*?-----END CERTIFICATE-----)',
        bundle,
        re.S,
    )
)

out = [
    "#pragma once",
    "",
    "// Generated by scripts/gen_root_ca.py from the Mozilla CA bundle (certifi). Do not edit.",
    "// The API certificate is verified against these roots; `insecure on` skips the check",
    "// and is meant for bench tests only.",
    "static const char kRootCaPem[] =",
]
for name in ROOTS:
    out.append(f"    // {name}")
    out.extend(f'    "{line}\\n"' for line in certs[name].splitlines())
out[-1] += ";"

target = pathlib.Path(__file__).resolve().parent.parent / "include" / "root_ca.h"
target.write_text("\n".join(out) + "\n", encoding="ascii", newline="\n")
print(f"wrote {target} with {len(ROOTS)} roots")
